"""Bounded real LOCAL synthesis for Ibex native first/held gate.

Use complete original RTL and confirmed OP plan, excluding failed OP templates.
Only syntax is schema-constrained. No predicate is preselected or rewritten.
"""
import argparse
import copy
import json
import os
from pathlib import Path
import shutil
import subprocess
import time
import urllib.request
import research59_phase_gate as g
from research_native_model import invoke
from research18_context_budget import count

P=g.ROOT/'deliverables/research59_prepare_20261023_r01'
SCHEMA=dict(type='object',additionalProperties=False,required=['operation','reason','assertions'],properties=dict(
    operation=dict(type='string',enum=['replace_op']),reason=dict(type='string'),
    assertions=dict(type='array',minItems=1,maxItems=3,items=dict(type='object',additionalProperties=False,
        required=['antecedent','consequent','timing','obligations'],properties=dict(
            antecedent=dict(type='string'),consequent=dict(type='string'),
            timing=dict(type='string',enum=['same_sample','next_sample']),
            obligations=dict(type='array',minItems=1,maxItems=1,items=dict(type='string',enum=['op_bit28_illegal'])))))))


def request(prep,feedback,seed):
    source=json.loads(g.read(prep/'request.preview.json')['messages'][1]['content'])
    stages=[]
    for r in g.read(prep/'phase_table.public.json'):
        stages.append({k:v for k,v in r.items() if k!='native_op_triggers'})
    # No old OP property template and no local positive-control expression.
    body={k:source[k] for k in ('case','source','rtl','confirmed_obligations','interface','legal_controls','timing','actual_model_op_rule','sampling_semantics')}
    body.update(current_assertions=dict(assertions=[g.read(prep/'protected_branch.json')]),
        native_development_samples=stages,
        task='Synthesize OP assertions anew from the confirmed obligation, original RTL and actual development samples. Keep BRANCH unchanged; return only OP properties. Determine every Boolean operand and timing yourself. Required checks must cover both instr_new=1 and held instr_new=0 samples. Illegal instruction means illegal_insn must be asserted. Legal control encodings must not fail. No successful OP property is supplied.',
        output_contract=dict(schema=SCHEMA,allowed_identifiers=sorted(g.prior.prior.native_flow.ALLOWED)),
        acceptance='Native first3+held9 detection and triggers, all9 development transactions without false alarms or unknown, then complete115 history+36 search and preservation of420 OP+270 BRANCH detections.',
        actual_feedback=feedback)
    return dict(model='qwen2.5-coder:7b-instruct',stream=True,format=SCHEMA,keep_alive='30m',
        options=dict(seed=seed,temperature=0,num_predict=768,num_ctx=32768,num_gpu=0,num_thread=8),
        messages=[dict(role='system',content='Generate SystemVerilog assertion predicates from the provided original RTL and confirmed functional requirements. Return only the declared JSON. Every predicate and temporal choice is generated by you; the framework does not correct semantic mistakes.'),dict(role='user',content=json.dumps(body,separators=(',',':')))])


def run(out,iterations=2,timeout=900,context_validator=None):
    out.mkdir(parents=True,exist_ok=False);owned=None;calls=[];accepted=None;decisions=[]
    for n,h in g.read(P/'sealed.json').items():assert g.old.digest(P/n)==h,n
    for n,h in g.read(P/'source_hashes.json').items():assert g.old.digest(g.ROOT/'scripts'/n)==h,n
    shutil.copy2(__file__,out/'runner_snapshot.py')
    g.dump(out/'protocol.json',dict(scope='research60_local_original_ibex',backend='local_ollama',maximum_calls=iterations,remote_calls=0,retries=0,
        timeout_seconds=timeout,source_preparation=P.relative_to(g.ROOT).as_posix(),
        changes='Local7B model; fresh OP synthesis without failed OP templates. Complete RTL, same native gates. Not a controlled model comparison.',
        independent='Not generated or used. No model response fabricated; no predicate rewrite.'))
    first=request(P,None,6001);g.dump(out/'request.preview.json',first)
    # Isolation checks are about context, not model correctness.
    content=json.loads(first['messages'][1]['content'])
    if context_validator is None:
        assert content['rtl']==json.loads(g.read(P/'request.preview.json')['messages'][1]['content'])['rtl']
    else:context_validator(content['rtl'])
    assert len(content['current_assertions']['assertions'])==1
    for p in g.read(P/'refinement_candidate.json')['assertions'][1:]:assert p['antecedent'] not in json.dumps(first)
    positive=g.read(P/'qualification/local_positive/candidate.json')
    assert positive['assertions'][1]['antecedent'] not in json.dumps(first)
    feedback=None;current=g.read(P/'shared_initial.json');known=g.read(P/'known_rejected_sets.json')
    try:
        try:urllib.request.urlopen('http://127.0.0.1:11434/api/tags',timeout=2).close()
        except Exception:
            env=os.environ.copy();env.update(OLLAMA_HOST='127.0.0.1:11434',OLLAMA_FLASH_ATTENTION='true',OLLAMA_KV_CACHE_TYPE='q8_0',OLLAMA_NUM_PARALLEL='1')
            with (out/'server.log').open('w') as log:owned=subprocess.Popen(['ollama','serve'],stdout=log,stderr=log,env=env,start_new_session=True)
            g.dump(out/'owned_service.json',dict(pid=owned.pid))
            for _ in range(30):
                try:urllib.request.urlopen('http://127.0.0.1:11434/api/tags',timeout=2).close();break
                except Exception:time.sleep(.5)
            else:raise RuntimeError('local_service_unavailable')
        tags=json.load(urllib.request.urlopen('http://127.0.0.1:11434/api/tags',timeout=5));g.dump(out/'model_tags.json',tags)
        digest=next(m['digest'] for m in tags['models'] if m['name']==first['model'])
        load=dict(model=first['model'],prompt='',stream=False,keep_alive='30m',options=first['options']);g.dump(out/'model_load/request.json',load)
        start=time.monotonic()
        response=json.load(urllib.request.urlopen(urllib.request.Request('http://127.0.0.1:11434/api/generate',data=json.dumps(load).encode(),headers={'Content-Type':'application/json'}),timeout=120))
        g.dump(out/'model_load/response.json',response);g.dump(out/'model_load/result.json',dict(management_calls=1,generation_calls=0 if response.get('response','')=='' else None,wall_seconds=time.monotonic()-start))
        assert response.get('response','')=='' and response.get('done'),'unexpected_load_response'
        for i in range(iterations):
            folder=out/f'v{i}';req=request(P,feedback,6001+i)
            preflight,_=count(req);rendered=preflight.pop('prompt');g.dump(folder/'context_preflight/result.json',preflight)
            (folder/'context_preflight/rendered_prompt.txt').write_text(rendered)
            if not preflight['fits_with_output_reserve']:
                g.dump(folder/'context_preflight/rejected_request.json',req);raise RuntimeError('local_context_overflow_before_generation')
            print('LOCAL_GENERATION',i,'context_tokens',preflight['rendered_prompt_tokens'],flush=True)
            call,text=invoke(req,folder/'model_call',g.dump,digest,timeout=timeout);calls.append(call);candidate=None
            decision=dict(accepted=False,reasons=[dict(kind='local_model_response_unusable',status=call['status'])])
            observed=call.get('prompt_tokens')
            if observed is not None and abs(observed-preflight['rendered_prompt_tokens'])>preflight['wrapper_margin_tokens']:
                decision=dict(accepted=False,reasons=[dict(kind='context_rendering_mismatch')])
            elif call['status']=='response_received':
                try:
                    value=json.loads(text);g.dump(folder/'model_call/model_edit.json',value)
                    candidate,labels=g.prior.diagnostic.adapt(value,current)
                    g.dump(folder/'model_call/candidate.json',candidate);g.dump(folder/'model_call/label_mapping.json',labels)
                    (folder/'model_call/candidate.sva').write_text('\n'.join(a['property'] for a in candidate['assertions'])+'\n')
                    novelty=g.prior.prior.previous.novelty(candidate,known);g.dump(folder/'model_call/novelty.json',novelty)
                    if not novelty['accepted']:candidate=None;decision=dict(accepted=False,reasons=novelty['reasons'])
                    else:known.append(dict(source=str(folder/'model_call/candidate.json'),signature=g.prior.prior.previous.op_signature(candidate)))
                except (ValueError,TypeError,KeyError,AssertionError) as exc:
                    candidate=None;decision=dict(accepted=False,reasons=[dict(kind='interface_rejected',detail=str(exc))])
            if candidate:
                result,gate=g.alignment(candidate,P,folder/'alignment');g.prior.diagnostic.audit_native(folder/'alignment',candidate,P,'alignment')
                decision=dict(accepted=False,reasons=[dict(kind='native_small_gate_failure')])
                feedback=dict(actual_model_proposal=value,native_counts=result['counts'],first_and_held=gate['focus12']['phases'],required_untriggered=gate['required_untriggered'],actual_evidence=g.old.evidence(result))
                if gate['accepted']:
                    h=g.old.replay(candidate,g.read(P/'history_cases.json'),'history',folder/'history',P)
                    s=g.old.replay(candidate,g.read(P/'search_cases.json'),'search',folder/'search',P)
                    for cohort in ('history','search'):g.prior.diagnostic.audit_native(folder/cohort,candidate,P,cohort)
                    combined=g.prior.prior.common.combine(h,s)
                    decision=g.prior.preserve(g.read(P/'baseline_full.json'),combined,g.read(P/'target_preservation.private.json'),g.old.decide)
                    guards={c:g.prior.prior.native_flow.prior.all_property_guard(r,{rev:g.read(folder/c/rev/'result.json') for rev in ('before','after')},candidate) for c,r in [('history',h),('search',s)]}
                    g.dump(folder/'all_property_guard.json',guards);g.dump(folder/'mapping.json',dict(history=h['mapping'],search=s['mapping']))
                    for c,guard in guards.items():
                        if not guard['accepted']:decision['accepted']=False;decision['reasons'].append(dict(kind='all_property_false_alarm_or_unknown',cohort=c,details=guard))
                    feedback=dict(actual_model_proposal=value,history=g.old.evidence(h),search=g.old.evidence(s),decision=g.prior.prior.common.gate_feedback(decision))
                    if decision['accepted']:
                        accepted=candidate;g.dump(out/'accepted_candidate.json',candidate)
                        g.dump(out/'acceptance.json',dict(sha256=g.old.acceptance.sha(candidate),history=h['counts'],search=s['counts'],decision=decision))
                print('LOCAL_NATIVE',i,gate['focus12']['phases'],'accepted',decision['accepted'],flush=True)
            else:feedback=dict(actual_model_text=text,decision=decision)
            g.dump(folder/'decision.json',decision);decisions.append(dict(version=i,accepted=decision['accepted']))
            g.dump(folder/'model_call/result.json',call)
            if accepted or call['status']!='response_received':break
    except Exception as exc:
        g.dump(out/'exception.json',dict(type=type(exc).__name__,detail=str(exc)))
        raise
    finally:
        if owned:
            owned.terminate()
            try:owned.wait(timeout=15)
            except subprocess.TimeoutExpired:pass
            g.dump(out/'service_shutdown.json',dict(pid=owned.pid,owned=True,returncode=owned.poll()))
        recorded_calls=[g.read(p) for p in out.glob('v*/model_call/transport_result.json')]
        g.dump(out/'outcome.json',dict(status='accepted_development_only' if accepted else 'no_accepted_sva',calls=len(recorded_calls),remote_calls=0,
            decisions=decisions,accepted_candidate_sha256=g.old.acceptance.sha(accepted) if accepted else None,independent_test='not_run'))
        g.dump(out/'cost.json',g.old.cost_audit(out,[p for p in out.rglob('*') if p.is_file()]))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True);p.add_argument('--iterations',type=int,choices=(1,2),default=2);p.add_argument('--timeout',type=int,choices=(900,1800),default=900)
    a=p.parse_args();run(a.out.resolve(),a.iterations,a.timeout)

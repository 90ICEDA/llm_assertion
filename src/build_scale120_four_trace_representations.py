from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
from pathlib import Path

from run_multi_model_small_eval import build_case_bundles
from run_trace_representation_ablation import build_trace_payloads, load_manifest_lookup, load_temporal_summary_lookup
from trace_representation_contract import TRACE_REPRESENTATIONS, case_contract_inputs, validate_temporal_relation_abstraction


ROOT = Path(__file__).resolve().parents[1]
METHOD_MAP = {
    "raw_trace": "spec_rtl_raw_trace",
    "naive_summary": "spec_rtl_naive_summary",
    "event_abstraction": "spec_rtl_event_abstraction",
    "temporal_relation_abstraction": "spec_rtl_temporal_relation_abstraction",
}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parent_id(case_id: str, case_meta: dict) -> str:
    explicit = str(case_meta.get("parent_bug_id", "")).strip()
    if explicit:
        return explicit
    match = re.search(r"_from_(case\d+_.+)$", case_id)
    return match.group(1) if match else case_id


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=str(ROOT / "rtl_cases_real_scale120"))
    parser.add_argument("--temporal", default=str(ROOT / "outputs/formal_temporal_abstractions/temporal_abstractions.json"))
    parser.add_argument("--output-dir", default=str(ROOT / "outputs/formal_four_trace_representations"))
    args = parser.parse_args()
    cases_root = Path(args.root).resolve(); temporal_path = Path(args.temporal).resolve(); out = Path(args.output_dir).resolve()
    out.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((cases_root / "case_manifest.json").read_text(encoding="utf-8"))
    case_ids = [item["name"] for item in manifest["cases"]]
    meta = load_manifest_lookup(cases_root); temporal = load_temporal_summary_lookup(temporal_path)
    bundles = build_case_bundles(cases_root=cases_root, case_ids=case_ids, abstracted_summary_lookup=temporal)
    records, audit_rows = [], []
    for bundle in bundles:
        case_id = bundle["case_id"]
        summary_json = cases_root / case_id / "experiment" / "trace_summary.json"
        bundle["trace_summary_json"] = json.loads(summary_json.read_text(encoding="utf-8")) if summary_json.exists() else {}
        payloads = build_trace_payloads(bundle, meta[case_id])
        # Preserve the already-evaluated canonical event-arm title. The body is
        # generated by the same deterministic builder; changing only this label
        # would force a scientifically redundant model rerun.
        payloads["spec_rtl_event_abstraction"] = payloads["spec_rtl_event_abstraction"].replace(
            "Event abstraction:", "Event-level trace abstraction:", 1
        )
        representations = {name: payloads[method] for name, method in METHOD_MAP.items()}
        errors = []
        if set(representations) != set(TRACE_REPRESENTATIONS): errors.append("wrong_representation_set")
        if not representations["raw_trace"].startswith("Good trace"): errors.append("raw_missing_good_header")
        if "Bad trace" not in representations["raw_trace"]: errors.append("raw_missing_bad_header")
        if not representations["naive_summary"].startswith("Naive trace summary:"): errors.append("naive_wrong_header")
        if not representations["event_abstraction"].startswith("Event-level trace abstraction:"): errors.append("event_wrong_header")
        errors.extend(validate_temporal_relation_abstraction(
            representations["temporal_relation_abstraction"],
            **case_contract_inputs(cases_root / case_id, meta[case_id]),
        ))
        if any(not str(value).strip() for value in representations.values()): errors.append("empty_representation")
        record = {
            "case_id": case_id,
            "parent_bug_id": parent_id(case_id, meta[case_id]),
            "representations": representations,
            "provenance": {
                "raw": [f"{case_id}/experiment/trace_good.txt", f"{case_id}/experiment/trace_bad.txt"],
                "naive": f"{case_id}/experiment/trace_summary.txt",
                "event": "deterministic event abstraction from trace summary; no golden or mutation input",
                "temporal": str(temporal_path),
                "uses_golden_sva": False, "uses_mutation_diff": False, "uses_buggy_rtl": False,
            },
        }
        records.append(record)
        audit_rows.append({"case_id": case_id, "parent_bug_id": record["parent_bug_id"], "pass": not errors, "errors": ";".join(sorted(set(errors))), "representation_count": len(representations)})
    artifact = out / "trace_representations.json"
    artifact.write_text(json.dumps(records, indent=2, ensure_ascii=False), encoding="utf-8")
    csv_path = out / "contract_audit.csv"
    with csv_path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(audit_rows[0])); writer.writeheader(); writer.writerows(audit_rows)
    summary = {
        "schema_version": 1, "fixed_representations": list(TRACE_REPRESENTATIONS),
        "audited_cases": len(audit_rows), "unique_parent_count": len({row["parent_bug_id"] for row in audit_rows}),
        "pass_cases": sum(row["pass"] for row in audit_rows), "fail_cases": sum(not row["pass"] for row in audit_rows),
        "all_pass": all(row["pass"] for row in audit_rows), "temporal_source_sha256": sha256(temporal_path),
        "artifact_sha256": sha256(artifact), "audit_csv_sha256": sha256(csv_path),
    }
    summary_path = out / "contract_audit_summary.json"
    summary_path.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    if not summary["all_pass"]: raise SystemExit(1)


if __name__ == "__main__": main()

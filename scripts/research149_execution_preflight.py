"""Local execution-binding checks in addition to sealed replication preflight."""
import argparse
from pathlib import Path
from unittest.mock import patch
import research148_stability_execution as b
import research147_stability_preflight as prior


def audit(prep,out):
    b.prepmod.verify(prep);out.mkdir(parents=True,exist_ok=False)
    with patch.object(prior,'b',b):prior.audit(prep,out/'controller')
    checks=[]
    def check(name,ok):
        assert ok,name
        checks.append(name)
    def rejects(name,action):
        try:action()
        except (AssertionError,KeyError,FileNotFoundError):check(name,True)
        else:raise AssertionError(name)
    candidate=b.read(prep/'cells'/b.read(prep/'cells.json')[0]['id']/'initial.json')
    sha=b.c.x.old.acceptance.sha(candidate)
    folder=out/'local_binding_fixture';version=folder/'tested_versions'/sha
    b.dump(version/'candidate.json',candidate)
    rejects('before_global_freeze',lambda:b.bind_shared_inputs(folder,version))
    b.dump(folder/'global_freeze.json',dict(unique_test_versions=[sha]))
    b.dump(folder/'test_generation.json',dict(freeze_sha256='wrong',model_dispatch_finished=True))
    rejects('wrong_freeze_binding',lambda:b.bind_shared_inputs(folder,version))
    generation=dict(freeze_sha256=b.digest(folder/'global_freeze.json'),model_dispatch_finished=False)
    b.dump(folder/'test_generation.json',generation)
    rejects('model_still_running',lambda:b.bind_shared_inputs(folder,version))
    generation['model_dispatch_finished']=True;b.dump(folder/'test_generation.json',generation)
    # Explicit local file-binding fixture: not generated by the independent
    # sampler and never passed to RTL, prompts, selection or acceptance rules.
    b.dump(folder/'independent_cases.json',[dict(local_binding_fixture_not_test=True,instruction=0)])
    b.bind_shared_inputs(folder,version)
    check('exact_input_copy',b.digest(folder/'independent_cases.json')==b.digest(version/'independent_cases.json'))
    check('candidate_unchanged',b.c.x.old.acceptance.sha(b.read(version/'candidate.json'))==sha)
    check('binding_saved',b.read(version/'shared_inputs_binding.json')['candidate_sha256']==sha)
    rejects('no_rebinding',lambda:b.bind_shared_inputs(folder,version))
    rejects('unknown_version',lambda:b.bind_shared_inputs(folder,folder/'tested_versions'/'unknown'))
    check('no_calls',not list(out.rglob('attempt.json')))
    check('no_native',not list(out.rglob('execute.json')))
    b.prepmod.verify(prep)
    previous=b.read(out/'controller/audit.json')
    b.dump(out/'audit.json',dict(passed=True,checks=checks,check_count=len(checks)+previous['check_count'],
        model_calls=0,new_native_executions=0,new_independent_tests=0,local_binding_fixture_is_not_independent_data=True,
        prepared_sha256=b.digest(prep/'sealed.json'),entry_point='scripts/research148_stability_execution.py'))
    protocol=b.read(prep/'protocol.json');qualification=b.read(prep/'qualification.json')
    (out/'SUMMARY.md').write_text('\n'.join(['# Candidate and seed replication readiness','',
        f"Local checks: {len(checks)+previous['check_count']}; cached original development rows: {qualification['raw_development_rows_reaudited']}.",
        f"All {qualification['eligible']} qualified candidates × 3 seeds = {protocol['cells']} cells; {qualification['behavior_profiles']} behavior profiles; one Ibex parent.",
        f"Maximum new model calls: {protocol['maximum_model_calls']}. No authorization granted or calls dispatched for this protocol.",
        'Entry point: scripts/research148_stability_execution.py. Per-cell research142 state machine and research139 native acceptance unchanged.',
        'All terminal versions freeze before one shared new96-word/four-configuration batch. Per-version raw audit binds that exact input; identical version hashes execute once.',
        'Generation full acceptance / actual first dispatches; conditional recovery / qualified regression opportunities (null when zero); independent H pass / eligible H trials, plus unique-version and planned-schedule rates.',
        'Unknown, missing tests, transport failure, not-run cells, physical model/token/native cost stay explicit. Correlated candidates do not establish cross-parent generalization.',
        'research145 r01 and research147 r01 remain local artifacts, not model experiments. r02 binds the corrected independent-input execution wrapper.'])+'\n',encoding='utf-8')
    b.dump(out/'sealed.json',{f.relative_to(out).as_posix():b.digest(f) for f in out.rglob('*') if f.is_file()})
    print('PREFLIGHT149',len(checks)+previous['check_count'],'checks; model0',flush=True)


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--prepared',type=Path,required=True);ap.add_argument('--out',type=Path,required=True)
    a=ap.parse_args();audit(a.prepared.resolve(),a.out.resolve())

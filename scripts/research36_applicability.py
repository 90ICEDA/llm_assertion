"""Check model event claims before accepting its original three-way labels.

This is a development-plan validator, not an SVA interpreter. All hardware
truth comes from qualified native records and the independent transaction oracle.
"""
import copy
import json
from research34_applicability import certificate, validate_plan, portable
import research17_loop as loop


def validate_events(value, expected):
    reasons = []
    projected = []
    truths = {r['id']: r for r in expected}
    certificates = []
    if not isinstance(value, dict) or set(value) != {'windows'} or not isinstance(value['windows'], list):
        return dict(accepted=False, reasons=[dict(kind='event_plan_schema')], stage='event_then_applicability')
    for row in value['windows']:
        if not isinstance(row, dict) or set(row) != {'id', 'anchor_cycle', 'check_cycle', 'pending', 'reset', 'applicability'}:
            reasons.append(dict(kind='event_row_schema'))
            continue
        projected.append({k: row[k] for k in ('id', 'anchor_cycle', 'check_cycle', 'applicability')})
        truth = truths.get(row['id']) if isinstance(row['id'], str) else None
        if not truth:
            reasons.append(dict(kind='unrecognized_window'))
            continue
        path = portable(truth['source'])
        from research34_campaign import digest
        if digest(path) != truth['source_sha256']:
            reasons.append(dict(kind='native_record_changed', id=row['id']))
            continue
        cert = certificate(loop.read(path), truth['check_cycle'])
        if cert['applicability'] == 'unknown' or any(cert.get(k) != truth[k] for k in ('anchor_cycle', 'check_cycle', 'applicability')):
            reasons.append(dict(kind='unqualified_or_changed_oracle', id=row['id']))
            continue
        prev, now = cert['samples']
        facts = dict(pending=bool(not prev['rst'] and prev['mvalid'] and not prev['mready']), reset=bool(now['rst']))
        for key, actual in facts.items():
            if type(row[key]) is not bool or row[key] != actual:
                reasons.append(dict(kind='incorrect_event_' + key, id=row['id'], expected=actual, actual=row[key]))
        # Consistency of the MODEL's own event claims. The independent oracle
        # still decides the expected label; this does not manufacture a plan.
        if type(row['pending']) is bool and type(row['reset']) is bool:
            consequence = 'cancelled' if row['pending'] and row['reset'] else 'required' if row['pending'] else 'not_required'
            if row['applicability'] != consequence:
                reasons.append(dict(kind='label_inconsistent_with_model_events', id=row['id'], actual=row['applicability']))
        certificates.append(dict(id=row['id'], source=str(path), source_sha256=truth['source_sha256'], facts=facts, independent_label=cert['applicability']))
    labels = validate_plan(dict(windows=projected), expected)
    reasons.extend(labels['reasons'])
    return dict(accepted=not reasons, reasons=reasons, stage='event_then_applicability',
                labels=labels, certificates=certificates, windows=len(expected),
                scope='Qualified development windows only. Original three-way acceptance retained. No property is generated by this validator.')


def request_from_previous(prepared, prior):
    request = copy.deepcopy(loop.read(prepared / 'request.preview.json'))
    body = json.loads(request['messages'][1]['content'])
    # Both contradictory ACTUAL rejections are development feedback. Never send
    # the full local answer/certificate table or an archived successful SVA.
    body.pop('prior_actual_model_plan', None)
    body.pop('prior_actual_rejection', None)
    body['prior_actual_attempts'] = [dict(plan=loop.read(prior / 'plan' / v / 'model_call/applicability_plan.json'),
                                        rejection=loop.read(prior / 'plan' / v / 'decision.json')) for v in ('v0', 'v1')]
    body['task'] = 'Identify obligation applicability by first reporting observed causal events, then classifying their consequence. Do not generate SVA.'
    body['event_semantics'] = dict(
        pending='Boolean: at anchor_sample, reset is inactive and an output is valid but not accepted (ready is low). This establishes a next-sample hold obligation.',
        reset='Boolean: reset is active at check_sample, regardless of anchor reset.',
        classification='cancelled only if an obligation was pending and reset cancels it at check_sample; required if pending and not cancelled; not_required if no obligation was pending. A reset release does not itself cancel a pending obligation. Current output validity and input-side requests do not determine whether the check is required.')
    body['response_schema'] = dict(windows=[dict(id='given window id', anchor_cycle='integer', check_cycle='integer',
                                              pending='boolean', reset='boolean', applicability=['required', 'cancelled', 'not_required', 'unknown'])])
    body['validation'] = 'All event booleans, cycles and original three-way labels are checked independently against the native transaction/reset records. No boolean or label is silently corrected. Missing, inconsistent or unknown claims stop before SVA generation.'
    request['messages'][1]['content'] = json.dumps(body)
    return request

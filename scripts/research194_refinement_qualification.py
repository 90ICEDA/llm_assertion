"""Real native wiring controls only; every edit here is handwritten, zero LLM."""
import argparse
import copy
from pathlib import Path
import research194_refinement as r
import research194_refinement_runner as run
import research194_cases as cases

def qualify(out):
    out=Path(out);out.mkdir(parents=True,exist_ok=False)
    sources={str(Path(module.__file__).resolve()):run.file_hash(module.__file__) for module in (r,run,cases)}
    run.dump(out/'loaded_source_bindings.json',sources)
    adapter=run.CaseAdapter('counter');initial=adapter.case['initial']
    query=cases.query_pool('counter',seed=19407)[0]
    baseline=adapter.evaluate(initial,out/'baseline',[query])
    evidence=run.model_evidence(baseline)
    bad_edit=dict(edits=[dict(op='replace_field',assertion='small_up',field='antecedent',value='en && !load && !clr && !down && q < 2')],reason='Handwritten negative control: lose known trigger coverage.')
    c=r.Controller(initial,'R3',adapter.case['obligations'],protected=set(baseline['detected_ids']))
    bad,edit=c.parse(bad_edit,evidence,adapter.validate)
    bad_m=adapter.evaluate(bad,out/'failed_local',[query]);local=c.observe(bad,bad_m,baseline=baseline,edit_record=edit)
    if c.stage!='compose':raise AssertionError('native_local_failure_did_not_enable_composition')
    full=dict(label='all_up',antecedent='en && !load && !clr && !down',consequent="q == (($past(q) + 1) & 4'hf)",timing='next_sample',obligations=['counter_step','counter_boundary'])
    compose_response=dict(edits=[dict(op='add_assertion',assertion=full)],reason='Handwritten complementary full-domain up and wrap protection.')
    composed,edit=c.parse(compose_response,evidence,adapter.validate)
    composed_m=adapter.evaluate(composed,out/'successful_composition',[query]);good=c.observe(composed,composed_m,baseline=baseline,edit_record=edit)
    if not good['decision']['accepted']:raise AssertionError('composition_not_accepted')
    # Separate three-round path; same exact first negative native result reused
    # with an explicit physical-zero/logical-two record, never a new execution.
    d=r.Controller(initial,'R3',adapter.case['obligations'],protected=set(baseline['detected_ids']))
    d.observe(bad,bad_m,baseline=baseline)
    wrong=dict(full,consequent="q == (($past(q) + 2) & 4'hf)")
    wrong_response=dict(edits=[dict(op='add_assertion',assertion=wrong)],reason='Handwritten negative composition control: wrong increment.')
    wrong_candidate,edit=d.parse(wrong_response,evidence,adapter.validate)
    wrong_m=adapter.evaluate(wrong_candidate,out/'failed_composition',[query]);wrong_entry=d.observe(wrong_candidate,wrong_m,baseline=baseline,edit_record=edit)
    if d.stage!='regenerate':raise AssertionError('native_composition_failure_did_not_enable_regeneration')
    final_response=dict(assertions=[full],reason='Handwritten full replacement after two independently measured failed proposals.')
    final,edit=d.parse(final_response,evidence,adapter.validate)
    final_m=adapter.evaluate(final,out/'successful_regeneration',[query]);final_entry=d.observe(final,final_m,baseline=baseline,edit_record=edit)
    if not final_entry['decision']['accepted']:raise AssertionError('regeneration_not_accepted')
    structured=[]
    for name,operation,ant,timing in [
        ('delay_probe',dict(op='set_delay',expression='rst_n',cycles=1),'rst_n && $past(rst_n)','same_sample'),
        ('window_probe',dict(op='set_window',expression='rst_n',min_cycles=0,max_cycles=1,quantifier='any'),'rst_n','same_sample'),
        ('matching_load',dict(op='match_transaction',base_expression="1'b1",request_id='d',response_id='q',cycles=1),'load && !clr','next_sample')]:
        _,value=r.render_operation(dict(operation,assertion=name,field='consequent'))
        structured.append(dict(label=name,antecedent=ant,consequent=value,timing=timing,obligations=['counter_load']))
    _,exception=r.render_operation(dict(op='except_when',assertion='exception_load',field='antecedent',base_expression='load',exception='clr'))
    structured.append(dict(label='exception_load',antecedent=exception,consequent='q == $past(d)',timing='next_sample',obligations=['counter_load']))
    structured_m=adapter.evaluate(structured,out/'structured_operations',[query])
    if not structured_m['native_complete'] or not structured_m['reference_complete']:raise AssertionError('structured_native_unknown')
    ms=[baseline,bad_m,composed_m,wrong_m,final_m,structured_m]
    result=dict(provenance='handwritten qualification, not generated by an LLM or used as a model success',model_calls=0,
        case_id='counter',query=query,baseline=dict(targets=len(baseline['targets']),detected=len(baseline['detected_ids'])),
        local_failure=local,composition_success=good,composition_failure=wrong_entry,regeneration_success=final_entry,
        structured_operations=dict(native_complete=structured_m['native_complete'],false_positives=len(structured_m['false_positives']),operations=['set_delay','set_window','match_transaction','except_when']),
        actual_native_compile_attempts=sum(m['cost']['native_compile_attempts'] for m in ms),
        actual_native_execution_attempts=sum(m['cost']['native_execution_attempts'] for m in ms),
        reused_failure=dict(measurement_sha256=r.digest(bad_m),physical_jobs=0,logical_jobs=2),
        two_round_history=c.history,three_round_history=d.history)
    run.dump(out/'fixture_inputs.json',dict(local=bad_edit,compose=compose_response,failed_compose=wrong_response,regenerate=final_response))
    run.dump(out/'qualification.json',result)
    if any(run.file_hash(path)!=value for path,value in sources.items()):raise AssertionError('qualification_source_changed_while_running')
    run.dump(out/'source_unchanged.json',dict(passed=True,source_bindings=sources))
    return result

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--out',type=Path,required=True);a=ap.parse_args()
    m=qualify(a.out);print('QUALIFIED native_jobs='+str(m['actual_native_compile_attempts'])+' model_calls=0',flush=True)
